/**
 * Інтерфейс-стратегія: поведінка «оцінити порцію їжі та дати пораду».
 * Різні реалізації оцінюють порцію за різними критеріями (калорії, білок, обидва).
 */
public interface MealAdviceStrategy {

    /** Повертає текст поради для конкретної порції. */
    String evaluate(Product product);

    /** Коротка назва стратегії для виводу. За замовчуванням — загальна назва. */
    default String shortLabel() {
        return "Порада";
    }
}
